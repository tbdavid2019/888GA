import { clampString } from "@/lib/edge/utils";

import type { ClefClient } from "./clef-client";
import { defaultClefClient } from "./clef-client";
import type {
  ChoiceAnswer,
  NoulAnswer,
  ScoreAnswer,
  SystemOneQuestion,
} from "./types";

export interface VisitorTelemetryInput {
  userAgent: string;
  path: string;
  ipAsn?: string;
  clientHints?: Record<string, unknown>;
  requestsPerMin?: number;
  referer?: string;
  headers?: Record<string, string>;
}

export type VisitorBotType =
  | "real_browser_visitor"
  | "search_engine_indexer"
  | "automated_scraper"
  | "vulnerability_scanner";

export interface BotClassificationResult {
  isBot: boolean;
  botProbability: number;
  botType: VisitorBotType;
  typeConfidence: number;
  riskScore: number;
  riskConfidence: number;
  suggestedAction: "allow" | "challenge_turnstile" | "block_or_drop";
}

const RISK_LEVELS = [
  "Harmless (ordinary human or verified good search bot)",
  "Low risk (minor unusual header or harmless scraper)",
  "Moderate risk (aggressive rate or datacenter IP)",
  "High risk (credential/path probing or scraper farm)",
  "Severe threat (known exploit scanner or hostile DDoS)",
];

const SENSITIVE_HEADER_KEYS = new Set([
  "authorization",
  "cookie",
  "set-cookie",
  "x-api-key",
  "proxy-authorization",
  "cf-connecting-ip",
  "x-forwarded-for",
]);

export async function classifyVisitorBot(
  telemetry: VisitorTelemetryInput,
  client: ClefClient = defaultClefClient,
): Promise<BotClassificationResult | null> {
  const safeHeaders: Record<string, string> = {};
  if (telemetry.headers && typeof telemetry.headers === "object") {
    for (const [k, v] of Object.entries(telemetry.headers)) {
      if (
        !SENSITIVE_HEADER_KEYS.has(k.toLowerCase()) &&
        typeof v === "string"
      ) {
        safeHeaders[clampString(k.toLowerCase(), 40)] = clampString(v, 200);
      }
    }
  }

  const state = {
    user_agent: clampString(telemetry.userAgent || "", 500),
    path: clampString(telemetry.path || "/", 255),
    asn: clampString(telemetry.ipAsn || "unspecified", 40),
    requests_per_minute: telemetry.requestsPerMin ?? 1,
    referer: clampString(telemetry.referer || "(direct)", 255),
    client_hints: telemetry.clientHints || {},
    headers: safeHeaders,
  };

  const questions: Record<string, SystemOneQuestion> = {
    is_bot: {
      type: "noul",
      instructions:
        "Is this incoming request generated by an automated bot, script, or crawler rather than a human browsing with an interactive web browser?",
    },
    bot_type: {
      type: "choice",
      instructions: "What category best describes this visitor?",
      criteria: {
        real_browser_visitor:
          "Genuine human browsing with a standard web browser",
        search_engine_indexer:
          "Legitimate verified search engine bot (Googlebot, Bingbot, etc.)",
        automated_scraper:
          "Headless browser, content scraper, or price monitor bot",
        vulnerability_scanner:
          "Vulnerability scanner, admin-path prober, or hostile exploit script",
      },
    },
    risk_level: {
      type: "score",
      instructions:
        "Assess the security and abuse risk level of this incoming visitor.",
      criteria: RISK_LEVELS,
    },
  };

  const response = await client.evaluateDecision<{
    is_bot: NoulAnswer;
    bot_type: ChoiceAnswer<VisitorBotType>;
    risk_level: ScoreAnswer;
  }>(state, questions);

  if (!response?.answers) {
    return null;
  }

  const { is_bot, bot_type, risk_level } = response.answers;

  if (!is_bot || !bot_type || !risk_level) {
    return null;
  }

  const botProb =
    typeof is_bot.noul === "number" && Number.isFinite(is_bot.noul)
      ? is_bot.noul
      : 0;
  const riskScore =
    typeof risk_level.score === "number" && Number.isFinite(risk_level.score)
      ? risk_level.score
      : 0;
  const typeConf =
    typeof bot_type.confidence === "number" &&
    Number.isFinite(bot_type.confidence)
      ? bot_type.confidence
      : 0;
  const riskConf =
    typeof risk_level.confidence === "number" &&
    Number.isFinite(risk_level.confidence)
      ? risk_level.confidence
      : 0;

  let suggestedAction: "allow" | "challenge_turnstile" | "block_or_drop" =
    "allow";

  if (bot_type.choice === "vulnerability_scanner" || riskScore >= 3.5) {
    suggestedAction = "block_or_drop";
  } else if (botProb > 0.75 && bot_type.choice === "automated_scraper") {
    suggestedAction = "challenge_turnstile";
  }

  return {
    isBot: botProb >= 0.5,
    botProbability: Number(botProb.toFixed(2)),
    botType: bot_type.choice || "real_browser_visitor",
    typeConfidence: Number(typeConf.toFixed(2)),
    riskScore: Number(riskScore.toFixed(1)),
    riskConfidence: Number(riskConf.toFixed(2)),
    suggestedAction,
  };
}
